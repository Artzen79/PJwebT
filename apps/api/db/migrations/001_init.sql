CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TYPE user_role AS ENUM ('member', 'admin');
CREATE TYPE user_status AS ENUM ('active', 'suspended');
CREATE TYPE booking_status AS ENUM ('cart', 'pending_payment', 'paid', 'checked_in', 'completed', 'cancelled', 'expired');
CREATE TYPE payment_status AS ENUM ('pending', 'approved', 'rejected');

CREATE TABLE users (
  id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  email text NOT NULL UNIQUE,
  password_hash text NOT NULL,
  name text NOT NULL,
  phone text,
  avatar_url text,
  role user_role NOT NULL DEFAULT 'member',
  status user_status NOT NULL DEFAULT 'active',
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE sports (
  id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE,
  icon text NOT NULL DEFAULT '🏅'
);

-- whole-hour opening times (local Asia/Bangkok); slots are 1 hour each
CREATE TABLE courts (
  id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  sport_id int NOT NULL REFERENCES sports(id),
  name text NOT NULL,
  description text NOT NULL DEFAULT '',
  price_per_hour numeric(10,2) NOT NULL CHECK (price_per_hour >= 0),
  open_hour smallint NOT NULL DEFAULT 8,
  close_hour smallint NOT NULL DEFAULT 22,
  image_url text,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (0 <= open_hour AND open_hour < close_hour AND close_hour <= 24)
);

CREATE TABLE equipment (
  id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  sport_id int NOT NULL REFERENCES sports(id),
  name text NOT NULL,
  description text NOT NULL DEFAULT '',
  total_qty int NOT NULL CHECK (total_qty >= 0),
  rent_price numeric(10,2) NOT NULL CHECK (rent_price >= 0),
  deposit numeric(10,2) NOT NULL DEFAULT 0 CHECK (deposit >= 0),
  image_url text,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- status 'cart' = the member's open basket (one per member); total is always computed from the items
CREATE TABLE bookings (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code text NOT NULL UNIQUE,
  user_id int NOT NULL REFERENCES users(id),
  status booking_status NOT NULL DEFAULT 'cart',
  confirmed_at timestamptz,
  expires_at timestamptz,
  checkin_token uuid UNIQUE,
  reminder_sent_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX one_cart_per_user ON bookings (user_id) WHERE status = 'cart';

-- active = slot is held (confirmed and not cancelled/expired); cart items stay inactive
CREATE TABLE booking_slots (
  id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  booking_id int NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  court_id int NOT NULL REFERENCES courts(id),
  start_at timestamptz NOT NULL,
  end_at timestamptz NOT NULL,
  price numeric(10,2) NOT NULL,
  active boolean NOT NULL DEFAULT false,
  CHECK (start_at < end_at),
  CONSTRAINT no_overlap EXCLUDE USING gist (court_id WITH =, tstzrange(start_at, end_at) WITH &&) WHERE (active)
);

CREATE TABLE booking_equipment (
  id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  booking_id int NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  equipment_id int NOT NULL REFERENCES equipment(id),
  qty int NOT NULL CHECK (qty > 0),
  start_at timestamptz NOT NULL,
  end_at timestamptz NOT NULL,
  price numeric(10,2) NOT NULL,
  active boolean NOT NULL DEFAULT false,
  returned_at timestamptz,
  condition_note text,
  fine numeric(10,2) NOT NULL DEFAULT 0,
  CHECK (start_at < end_at)
);
CREATE INDEX booking_equipment_active ON booking_equipment (equipment_id) WHERE active;

CREATE TABLE payments (
  id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  booking_id int NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  amount numeric(10,2) NOT NULL,
  slip_path text NOT NULL,
  status payment_status NOT NULL DEFAULT 'pending',
  note text,
  reviewed_by int REFERENCES users(id),
  reviewed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE reviews (
  id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  booking_id int NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  user_id int NOT NULL REFERENCES users(id),
  court_id int NOT NULL REFERENCES courts(id),
  rating smallint NOT NULL CHECK (rating BETWEEN 1 AND 5),
  comment text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (booking_id, court_id)
);
